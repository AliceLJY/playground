// Bake the almanac for 手撕日历 into src/almanac.js. Run by hand; the page itself has no dependency.
//   npm i lunar-javascript@1.7.8 --prefix <some-temp-dir>          (MIT, https://github.com/6tail/lunar-javascript)
//   NODE_PATH=<some-temp-dir>/node_modules node tools/gen-almanac.cjs
// Range 2026-01-01 .. 2027-12-31. Statutory 休/班 days are only baked for 2026 (the published schedule);
// later years fall back to weekends, see SPEC.md.
const {Solar,HolidayUtil}=require('lunar-javascript');
const fs=require('fs'),path=require('path');
const START=[2026,1,1],END=[2027,12,31],HOLIDAY_YEARS=new Set([2026]);
const days=[];
let s=Solar.fromYmd(...START);
const end=Solar.fromYmd(...END).toYmd();
for(;;){
  const l=s.getLunar(),ymd=s.toYmd();
  const h=HOLIDAY_YEARS.has(s.getYear())?HolidayUtil.getHoliday(ymd):null;
  const fest=[...l.getFestivals(),...s.getFestivals()].filter((v,i,a)=>a.indexOf(v)===i);
  days.push({
    d:ymd,
    lm:l.getMonthInChinese()+'月',ld:l.getDayInChinese(),
    leap:l.getMonth()<0?1:0,
    y:l.getYearInGanZhi(),z:l.getYearShengXiao(),m:l.getMonthInGanZhi(),g:l.getDayInGanZhi(),
    jq:l.getJieQi()||'',f:fest.slice(0,2),
    yi:l.getDayYi().slice(0,8),ji:l.getDayJi().slice(0,8),
    c:l.getDayChongDesc(),sha:l.getDaySha(),
    h:h?(h.isWork()?'班':'休'):'',hn:h?h.getName():''
  });
  if(ymd===end)break;
  s=s.next(1);
}
const out=path.join(__dirname,'..','src','almanac.js');
fs.writeFileSync(out,'// Generated by tools/gen-almanac.cjs from lunar-javascript 1.7.8 (MIT). Do not edit by hand.\n'+
 '(function(root){const A='+JSON.stringify({start:days[0].d,days})+';if(typeof module===\'object\'&&module.exports)module.exports=A;else root.TearAlmanac=A;})(typeof self!==\'undefined\'?self:this);\n');
console.log('wrote',days.length,'days to',out,fs.statSync(out).size,'bytes');
